#!/bin/bash
# Fresh Ubuntu 24.04 only. No Remnawave panel, DNS, user or payment writes.
# TLS terminates at Nginx:443; Remnawave serves loopback gRPC/WS.
set -euo pipefail
umask 077
export LC_ALL=C

DOMAIN=
PANEL_HOST=panel.wayspn.online
ACCEPT_TOS=no
SSH_PORT=${SSH_CONNECTION:-}
SSH_PORT=${SSH_PORT##* }
SSH_PORT=${SSH_PORT:-22}
while [ "$#" -gt 0 ]; do
    case "$1" in
        --domain) DOMAIN=${2:?Domain required}; shift 2 ;;
        --panel-host) PANEL_HOST=${2:?Panel hostname required}; shift 2 ;;
        --ssh-port) SSH_PORT=${2:?SSH port required}; shift 2 ;;
        --agree-le-tos) ACCEPT_TOS=yes; shift ;;
        *) echo 'Usage: bash spn-direct-setup.sh --domain node.example.com [--panel-host panel.example.com] [--ssh-port 22] --agree-le-tos' >&2; exit 2 ;;
    esac
done
fail() { printf 'Stopped: %s\n' "$*" >&2; exit 1; }
trap 'printf "Setup stopped at line %s. No automatic retry or reinstall.\n" "$LINENO" >&2' ERR
[ "$(id -u)" = 0 ] || fail 'Run as root'
. /etc/os-release
[ "$ID:$VERSION_ID" = ubuntu:24.04 ] || fail 'This template requires clean Ubuntu 24.04'
[[ "$DOMAIN" =~ ^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$ ]] || fail 'Invalid domain'
[[ "$PANEL_HOST" =~ ^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$ ]] || fail 'Invalid panel hostname'
[[ "$SSH_PORT" =~ ^[0-9]{1,5}$ ]] && (( SSH_PORT >= 1 && SSH_PORT <= 65535 )) || fail 'Invalid SSH port'
[ "$ACCEPT_TOS" = yes ] || fail 'To issue a certificate, explicitly accept https://letsencrypt.org/repository/ using --agree-le-tos'
for p in 80 443 2222 10087 10088; do
    [ -z "$(ss -H -lnt "sport = :$p")" ] || fail "TCP$p is already occupied; do not use this installer on an existing node"
done
[ ! -e /opt/remnanode ] || fail '/opt/remnanode already exists; existing installation preserved'
[ ! -e /etc/nginx/sites-available/spn-direct.conf ] || fail 'Installer site already exists; inspect before retry'
[ ! -e /etc/nginx/sites-enabled/spn-direct.conf ] || fail 'Installer site already enabled'
if command -v docker >/dev/null && docker container inspect remnanode >/dev/null 2>&1; then
    fail 'An existing remnanode container was found'
fi
if command -v ufw >/dev/null && ufw status | grep -Fxq 'Status: active'; then
    fail 'Existing active firewall; review its rules separately'
fi
shopt -s nullglob
for p in /etc/nginx/sites-enabled/*; do
    [ "$p" = /etc/nginx/sites-enabled/default ] && [ -L "$p" ] \
      && [ "$(readlink "$p")" = /etc/nginx/sites-available/default ] || fail 'Existing Nginx site; not a clean server'
done
mapfile -t PANEL_IPS < <(getent ahostsv4 "$PANEL_HOST" | awk '{print $1}' | sort -u)
[ "${#PANEL_IPS[@]}" = 1 ] || fail 'Panel must resolve to exactly one IPv4; use its direct DNS hostname'
PANEL_IP=${PANEL_IPS[0]}
getent ahostsv4 "$DOMAIN" >/dev/null || fail 'Create the DNS-only A record before installation'
read -r -s -p 'Paste SECRET_KEY from the Remnawave node install configuration: ' NODE_SECRET
printf '\n'
[[ ${#NODE_SECRET} -ge 20 && "$NODE_SECRET" =~ ^[A-Za-z0-9_/+=-]+$ ]] || fail 'Expected the single-line node SECRET_KEY, not the panel API token'

export DEBIAN_FRONTEND=noninteractive
apt-get update
apt-get install -y ca-certificates docker.io docker-compose-v2 nginx certbot ufw
systemctl enable --now docker nginx
docker compose version >/dev/null

install -d -m 0700 /opt/remnanode /root/spn-direct-setup
printf 'NODE_PORT=2222\nSECRET_KEY=%s\n' "$NODE_SECRET" > /opt/remnanode/node.env
unset NODE_SECRET
chmod 0600 /opt/remnanode/node.env
cat > /opt/remnanode/docker-compose.yml <<'YAML'
services:
  remnanode:
    container_name: remnanode
    hostname: remnanode
    image: remnawave/node:3.4.1@sha256:0cdf386dd49f360fc885bb34bde21132e478e40f0deac62d616086ec0fa9257e
    restart: unless-stopped
    network_mode: host
    env_file:
      - node.env
    ulimits:
      nofile:
        soft: 65536
        hard: 65536
    logging:
      driver: json-file
      options:
        max-size: 20m
        max-file: '3'
YAML

install -d -m 0755 /var/www/spn-direct-acme
if [ -L /etc/nginx/sites-enabled/default ]; then
    mv /etc/nginx/sites-enabled/default /root/spn-direct-setup/nginx-default.before
fi
cat > /etc/nginx/sites-available/spn-direct.conf <<NGINX
# Generated by spn-direct-setup; DOMAIN=$DOMAIN
server {
    listen 80;
    server_name $DOMAIN;
    location ^~ /.well-known/acme-challenge/ {
        root /var/www/spn-direct-acme;
        try_files \$uri =404;
    }
    location / { return 404; }
}
NGINX
chmod 0644 /etc/nginx/sites-available/spn-direct.conf
ln -s /etc/nginx/sites-available/spn-direct.conf /etc/nginx/sites-enabled/spn-direct.conf
nginx -t
systemctl reload nginx

# Docker uses host networking: UFW protects the node API normally.
# Only the panel may reach 2222; transport backends stay on loopback.
ufw allow "$SSH_PORT/tcp" comment SPN-SSH
ufw allow 80/tcp comment SPN-ACME
ufw allow 443/tcp comment SPN-TLS
ufw allow from "$PANEL_IP" to any port 2222 proto tcp comment SPN-PANEL
ufw default deny incoming
ufw default allow outgoing
ufw --force enable

certbot certonly --webroot -w /var/www/spn-direct-acme \
    -d "$DOMAIN" --cert-name "$DOMAIN" --non-interactive \
    --agree-tos --register-unsafely-without-email

cp -p /etc/nginx/sites-available/spn-direct.conf /root/spn-direct-setup/bootstrap.before-tls.conf
cat > /etc/nginx/sites-available/spn-direct.conf <<NGINX
# Generated by spn-direct-setup; DOMAIN=$DOMAIN
server { listen 80 default_server; server_name _; return 444; }
server { listen 443 ssl default_server; server_name _; ssl_reject_handshake on; }
server {
    listen 80;
    server_name $DOMAIN;
    location ^~ /.well-known/acme-challenge/ {
        root /var/www/spn-direct-acme;
        try_files \$uri =404;
    }
    location / { return 301 https://$DOMAIN\$request_uri; }
}
server {
    listen 443 ssl http2;
    server_name $DOMAIN;
    ssl_certificate /etc/letsencrypt/live/$DOMAIN/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/$DOMAIN/privkey.pem;
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_session_cache shared:SPN_DIRECT:10m;
    ssl_session_timeout 1d;
    ssl_session_tickets off;
    server_tokens off;
    access_log off;
    if (\$host != $DOMAIN) { return 444; }
    if (\$ssl_server_name != $DOMAIN) { return 444; }
    location ^~ /spngrpc/ {
        grpc_pass grpc://127.0.0.1:10087;
        grpc_set_header Host $DOMAIN;
        grpc_set_header X-Real-IP \$remote_addr;
        grpc_set_header X-Forwarded-For \$remote_addr;
        grpc_set_header X-Forwarded-Proto https;
        grpc_set_header Forwarded "";
        grpc_connect_timeout 5s;
        grpc_read_timeout 3600s;
        grpc_send_timeout 3600s;
        grpc_next_upstream off;
        client_max_body_size 0;
        client_body_timeout 3600s;
    }
    location ^~ /direct/ws/ {
        proxy_pass http://127.0.0.1:10088;
        proxy_http_version 1.1;
        proxy_set_header Host $DOMAIN;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection "upgrade";
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$remote_addr;
        proxy_set_header X-Forwarded-Proto https;
        proxy_set_header Forwarded "";
        proxy_buffering off;
        proxy_cache off;
        proxy_connect_timeout 5s;
        proxy_read_timeout 3600s;
        proxy_send_timeout 3600s;
        add_header Cache-Control no-store always;
    }
    location = /health {
        default_type application/json;
        add_header Cache-Control no-store always;
        return 200 '{"status":"ok"}\n';
    }
    location / { return 404; }
}
NGINX
if ! nginx -t; then
    cp -p /root/spn-direct-setup/bootstrap.before-tls.conf /etc/nginx/sites-available/spn-direct.conf
    fail 'TLS configuration invalid; HTTP bootstrap retained'
fi
install -d -m 0755 /etc/letsencrypt/renewal-hooks/deploy
cat > /etc/letsencrypt/renewal-hooks/deploy/spn-direct-nginx <<'HOOK'
#!/bin/sh
set -eu
/usr/sbin/nginx -t
/usr/bin/systemctl reload nginx
HOOK
chmod 0755 /etc/letsencrypt/renewal-hooks/deploy/spn-direct-nginx
systemctl enable --now certbot.timer
systemctl reload nginx
docker compose -f /opt/remnanode/docker-compose.yml up -d
printf '\nReady: https://%s/health\nPanel control: TCP2222 from %s only.\nSelect the profile and both inbounds in Remnawave; add them to the intended squads.\n' "$DOMAIN" "$PANEL_IP"
